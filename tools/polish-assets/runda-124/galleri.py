def granska():
    import re
    fel = []
    sedda = {}
    for pid, rader in ALT.items():
        if len(rader) != len(FILER[pid]):
            fel.append(f"{pid}: {len(rader)} alt-texter mot {len(FILER[pid])} filer")
        for i, t in enumerate(rader, 1):
            if (pid, i) in BORT:
                if t is not None:
                    fel.append(f"{pid} pos {i}: borttagen bild ska ha None")
                continue
            if t is None:
                fel.append(f"{pid} pos {i}: saknar alt-text men ligger kvar")
                continue
            if len(t) > 125:
                fel.append(f"{pid} pos {i}: {len(t)} tecken (max 125)")
            if re.search(r"\b(homcom|outsunny|pawhut|aiyaplay|vinsetto|aosom)\b", t, re.I):
                fel.append(f"{pid} pos {i}: HUSMÄRKE — {t!r}")
            if re.search(r"\b\d{3}-\d{3}[A-Z0-9]*\b", t):
                fel.append(f"{pid} pos {i}: ARTIKELNUMMER — {t!r}")
            if re.search(r"\b(tyskland|kina|polen|spanien|eu-lager)\b", t, re.I):
                fel.append(f"{pid} pos {i}: LEVERANSLAND — {t!r}")
            if re.search(r"\b(werkzeug\w*|schublade\w*|stahl|kunststoff|farbe|"
                         r"schwarz|griff|abschließbar|staufach)\b", t, re.I):
                fel.append(f"{pid} pos {i}: TYSKT ORD — {t!r}")
            if i == 3 and not t.startswith("Måttritning"):
                fel.append(f"{pid} pos 3 är måttritningen och ska säga det — {t!r}")
            if i != 3 and t.startswith("Måttritning"):
                fel.append(f"{pid} pos {i}: bara position 3 är måttritning")
            n = t.strip().lower()
            if n in sedda:
                fel.append(f"{pid} pos {i}: DUBBLETT av {sedda[n]}")
            sedda[n] = f"{pid} pos {i}"
    return fel


